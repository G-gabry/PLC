def Calculate_brust_lengths(sequence):
    left=0
    brust_lengths=[]
    for right in range(len(sequence)):
        if sequence[right]==0:
           if sequence[left]==1:
             brust_lengths.append(right-left)
           left=right+1
    if left<len(sequence) and sequence[left]==1:
       brust_lengths.append(len(sequence)-left)
    return brust_lengths

def calculate_markov_transitions(sequence):
    """
    Calculates the transition probabilities for the Gilbert-Elliott model.
    Simple Version: We manually count every time the state changes.
    """
    if len(sequence) < 2:
        return 0.0, 0.0

    count_0_to_0 = 0
    count_0_to_1 = 0
    count_1_to_0 = 0
    count_1_to_1 = 0


    for i in range(len(sequence) - 1):
        current_packet = sequence[i]
        next_packet = sequence[i+1]

        if current_packet == 0:
            if next_packet == 0:
                count_0_to_0 += 1
            else:
                count_0_to_1 += 1
        else:
            if next_packet == 0:
                count_1_to_0 += 1
            else:
                count_1_to_1 += 1

    total_starts_at_0 = count_0_to_0 + count_0_to_1
    total_starts_at_1 = count_1_to_0 + count_1_to_1

    p01 = count_0_to_1 / total_starts_at_0 if total_starts_at_0 > 0 else 0.0
    p11 = count_1_to_1 / total_starts_at_1 if total_starts_at_1 > 0 else 0.0

    return p01, p11

