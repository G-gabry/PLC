def extract_bursts(sequence):
    """
    Extracts (start_packet_idx, burst_length) for all bursts (consecutive '1's) in a sequence.
    """
    bursts = []
    i = 0
    while i < len(sequence):
        if sequence[i] == 1:
            start_idx = i
            length = 0
            while i < len(sequence) and sequence[i] == 1:
                length += 1
                i += 1
            bursts.append((start_idx, length))
        else:
            i += 1
    return bursts

def detect_burst_lengths_in_files(filenames):
    """
    Finds all unique burst lengths that actually happened in the specified files
    and returns them in a sorted list.
    """
    all_burst_lengths = set()
    burst_examples_dict = {} # Dictionary to store examples: {burst_len: [(filename_base, start_idx), ...]}

    for name in filenames:
        trace_path = TRACES_DIR / f"{name}.txt"
        if not trace_path.exists():
            print(f"Warning: Trace file not found at {trace_path}")
            continue

        data = np.loadtxt(trace_path, dtype=int).flatten()
        if len(data) == 0:
            continue

        file_bursts = extract_bursts(data) # Use the newly defined extract_bursts
        for start_idx, length in file_bursts:
            all_burst_lengths.add(length)
            if length not in burst_examples_dict:
                burst_examples_dict[length] = []
            # Store up to 3 examples per burst length to avoid too many plots
            if len(burst_examples_dict[length]) < 3:
                burst_examples_dict[length].append((name, start_idx))

    return sorted(list(all_burst_lengths)), burst_examples_dict

