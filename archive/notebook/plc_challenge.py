def _get_parcnet(extra_dim, order, diagonal_load, context_dim, disable_nn, lite=True, device=None):
    device = device or ('cuda' if torch.cuda.is_available() else 'cpu')
    key = (PACKET_SIZE, extra_dim, lite, device, disable_nn)
    if key not in _parcnet_cache:
        _parcnet_cache[key] = PARCnet(
            model_checkpoint=MODEL_CHECKPOINT,
            packet_dim=PACKET_SIZE,
            extra_pred_dim=extra_dim,
            ar_order=order,
            ar_diagonal_load=diagonal_load,
            ar_context_dim=max(1, context_dim // PACKET_SIZE),
            nn_context_dim=max(1, context_dim // PACKET_SIZE),
            nn_fade_dim=64,
            device=device,
            lite=lite,
            disable_nn=disable_nn,
        )
    parcnet = _parcnet_cache[key]
    parcnet.ar_model = ARModel(order, diagonal_load)
    parcnet.ar_context_dim = max(1, context_dim // PACKET_SIZE) * PACKET_SIZE
    parcnet.nn_context_dim = max(1, context_dim // PACKET_SIZE) * PACKET_SIZE
    return parcnet

def Calculate_brust_lengths(sequence):
    left=0
    brust_lengths=[]
    for right in range(len(sequence)):
        if sequence[right]==0:
           if sequence[left]==1:
             brust_lengths.append(right-left)
           left=right+1
    if left<len(sequence) and sequence[left]==1:
       brust_lengths.append(len(sequence)-left)
    return brust_lengths

def calculate_markov_transitions(sequence):
    """
    Calculates the transition probabilities for the Gilbert-Elliott model.
    Simple Version: We manually count every time the state changes.
    """
    if len(sequence) < 2:
        return 0.0, 0.0

    count_0_to_0 = 0
    count_0_to_1 = 0
    count_1_to_0 = 0
    count_1_to_1 = 0


    for i in range(len(sequence) - 1):
        current_packet = sequence[i]
        next_packet = sequence[i+1]

        if current_packet == 0:
            if next_packet == 0:
                count_0_to_0 += 1
            else:
                count_0_to_1 += 1
        else:
            if next_packet == 0:
                count_1_to_0 += 1
            else:
                count_1_to_1 += 1

    total_starts_at_0 = count_0_to_0 + count_0_to_1
    total_starts_at_1 = count_1_to_0 + count_1_to_1

    p01 = count_0_to_1 / total_starts_at_0 if total_starts_at_0 > 0 else 0.0
    p11 = count_1_to_1 / total_starts_at_1 if total_starts_at_1 > 0 else 0.0

    return p01, p11

