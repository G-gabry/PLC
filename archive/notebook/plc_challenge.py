@njit
def _parcnet_predict_loop(past: np.ndarray, coeff: np.ndarray, steps: int) -> np.ndarray:
    prediction = np.zeros(steps)
    for i in range(steps):
        pred = np.dot(past, coeff)
        prediction[i] = pred
        past = np.roll(past, -1)
        past[-1] = pred
    return prediction


def ar_fit(past_audio, order, diagonal_load):
    """Fits AR(order) coefficients via autocorrelation + Levinson-Durbin -- same as PARCnet's ar_model.py."""
    acf = scipy.signal.correlate(past_audio, past_audio, mode='full')
    if np.any(np.isnan(acf)):
        acf = scipy.signal.correlate(past_audio, past_audio, mode='full', method='direct')

    zero_lag = len(acf) // 2
    c = acf[zero_lag:zero_lag + order].copy()
    c[0] += diagonal_load
    b = acf[zero_lag + 1:zero_lag + order + 1]
    return scipy.linalg.solve_toeplitz(c, b, check_finite=False)

def ar_predict(past_audio, order, diagonal_load, steps):
    """Fits AR(order) on past_audio, then extrapolates `steps` samples forward."""
    coeff = ar_fit(past_audio, order, diagonal_load)
    past_view = np.ascontiguousarray(past_audio[-order:], dtype=np.float32)
    coeff_view = np.ascontiguousarray(coeff[::-1], dtype=np.float32)
    pred = _parcnet_predict_loop(past=past_view, coeff=coeff_view, steps=steps)

    if np.any(np.isnan(pred)) or np.any(np.abs(pred) > 1.5):
        return np.zeros(steps)
    return pred

def lpc_conceal(audio, trace, order, diagonal_load, packet_size, extra_dim, context_dim, equal_power=True):
    """Packet-loss concealment with AR/LPC only -- PARCnet's own per-packet loop, minus the neural network."""
    pred_dim = packet_size + extra_dim
    output = np.pad(audio.copy(), (0, extra_dim))
    is_burst = False

    if extra_dim > 0:
        linear = np.linspace(0., 1., extra_dim)
        fade_in = np.sqrt(linear) if equal_power else linear
        fade_out = np.sqrt(1. - linear) if equal_power else 1. - linear

    for i, lost in enumerate(trace):
        if not lost:
            is_burst = False
            continue

        idx = i * packet_size
        valid = output[max(0, idx - context_dim):idx]
        valid = np.pad(valid, (context_dim - len(valid), 0))
        prediction = ar_predict(valid, order, diagonal_load, pred_dim)

        if extra_dim > 0:
            prediction[-extra_dim:] *= fade_out
            if is_burst:
                prediction[:extra_dim] *= fade_in
            output[idx + packet_size:idx + pred_dim] *= fade_in

        output[idx:idx + pred_dim] += prediction
        is_burst = True

    return output[:len(audio)]

def compare_all_methods(filename_base, start_packet_idx, burst_len_packets,
                         order=256, diagonal_load=0.001, context_dim=4096, extra_dim=256,
                         equal_power=False, context_ms=40, audio_context_ms=2000, example_num=1):
    """
    Compares 3 PLC methods on the same real burst: this file's own lpc_conceal ("this
    LPC"), the real PARCnet pipeline with the neural network's forward pass skipped
    ("LPC without NN"), and the real PARCnet pipeline with the neural network
    ("LPC with NN") -- both run live via the actual PARCnet inference class, not
    loaded from precomputed files, so this works on any file without a separate
    inference.py pre-processing step. Defaults match PARCnet's own
    order/diagonal_load/context_dim/extra_dim, so out of the box every method is on
    equal footing and differences reflect the algorithm, not mismatched settings.
    Prints the MSE between every pair over the gap itself (not the surrounding
    context) and returns it. Also saves a listenable WAV snippet (audio_context_ms of
    real audio on each side of the gap) for the broken original and each repaired
    method, into AUDIO_DIR, so the repair can be judged by ear, not just by eye.
    """
    lossy, sr = librosa.load(LOSSY_DIR / f'{filename_base}.wav', sr=None)
    trace = np.loadtxt(TRACES_DIR / f'{filename_base}.txt', dtype=int).flatten()

    this_lpc = lpc_conceal(lossy, trace, order, diagonal_load, PACKET_SIZE, extra_dim, context_dim, equal_power)
    lpc_without_nn = _get_parcnet(extra_dim, order, diagonal_load, context_dim, disable_nn=True)(lossy, trace)
    lpc_with_nn = _get_parcnet(extra_dim, order, diagonal_load, context_dim, disable_nn=False)(lossy, trace)

    gap_start = start_packet_idx * PACKET_SIZE
    gap_size = burst_len_packets * PACKET_SIZE
    gap_end = gap_start + gap_size

    signals = [
        ("this_lpc",       "This LPC (recursive)",      this_lpc,        "#2a78d6"),
        ("lpc_without_nn", "LPC without NN (pipeline)", lpc_without_nn,  "#e8871e"),
        ("lpc_with_nn",    "LPC with NN (PARCnet)",      lpc_with_nn,    "#1baf7a"),
    ]

    audio_context = int(sr * audio_context_ms / 1000)
    audio_win_start = max(0, gap_start - audio_context)
    audio_win_end = min(len(lossy), gap_end + audio_context)
    tag = f"{filename_base}_{burst_len_packets}pkt_ex{example_num}"
    sf.write(AUDIO_DIR / f"broken_{tag}.wav", lossy[audio_win_start:audio_win_end], sr)
    for name, _, sig, _ in signals:
        sf.write(AUDIO_DIR / f"{name}_{tag}.wav", sig[audio_win_start:audio_win_end], sr)

    context = int(sr * context_ms / 1000)
    win_start = max(0, gap_start - context)
    win_end = min(len(lossy), gap_end + context)
    t_ms = (np.arange(win_start, win_end) - gap_start) / sr * 1000
    gap_end_ms = gap_size / sr * 1000
    y_max = max(np.max(np.abs(sig[win_start:win_end])) for _, _, sig, _ in signals) * 1.1

    fig, axes = plt.subplots(2, 3, figsize=(15, 8), gridspec_kw={"height_ratios": [1, 1.15]})

    for col, (_, label, sig, color) in enumerate(signals):
        ax = axes[0, col]
        ax.plot(t_ms, sig[win_start:win_end], color=color, linewidth=1.1)
        ax.axvspan(0, gap_end_ms, color="black", alpha=0.08)
        ax.set_title(label, fontsize=10, color=color)
        ax.set_ylim(-y_max, y_max)
        ax.set_xlabel("Time relative to gap start (ms)")
        if col == 0:
            ax.set_ylabel("Amplitude")

    specs_db = {}
    for name, _, sig, _ in signals:
        stft = librosa.stft(sig[win_start:win_end], n_fft=1024, hop_length=64)
        specs_db[name] = librosa.amplitude_to_db(np.abs(stft), ref=np.max)
    vmin = min(s.min() for s in specs_db.values())
    vmax = max(s.max() for s in specs_db.values())

    for col, (name, label, _, color) in enumerate(signals):
        ax = axes[1, col]
        img = librosa.display.specshow(specs_db[name], sr=sr, hop_length=64, x_axis="time", y_axis="hz",
                                        ax=ax, cmap="magma", vmin=vmin, vmax=vmax)
        ax.set_title(f"Spectrogram — {label}", fontsize=9, color=color)
        ax.set_ylim(0, 8000)
        ax.set_xlabel("Time (s)")
        if col == 0:
            ax.set_ylabel("Frequency (Hz)")

    fig.colorbar(img, ax=axes[1, :], format="%+2.0f dB", fraction=0.02, pad=0.02, label="Magnitude (dB)")
    fig.suptitle(f"{filename_base} — {burst_len_packets}-packet burst, example {example_num}", fontsize=13, y=1.0)
    fig.savefig(FIGURES_DIR / f"compare_{filename_base}_{burst_len_packets}pkt_ex{example_num}.png",
                dpi=150, bbox_inches='tight')
    plt.show()

    diff_pairs = [(i, j) for i in range(len(signals)) for j in range(i + 1, len(signals))]
    diffs = [signals[i][2][win_start:win_end] - signals[j][2][win_start:win_end] for i, j in diff_pairs]
    diff_y_max = max(np.max(np.abs(d)) for d in diffs) * 1.1

    diff_fig, diff_axes = plt.subplots(1, 3, figsize=(15, 4))
    rows = []
    for ax, (i, j), diff in zip(diff_axes.flat, diff_pairs, diffs):
        name_a, label_a, sig_a, _ = signals[i]
        name_b, label_b, sig_b, _ = signals[j]
        gap_mse = np.mean((sig_a[gap_start:gap_end] - sig_b[gap_start:gap_end]) ** 2)
        rows.append({'pair': f'{name_a} vs {name_b}', 'gap_mse': gap_mse})

        ax.plot(t_ms, diff, color="#7d5ba6", linewidth=1.0)
        ax.axvspan(0, gap_end_ms, color="black", alpha=0.08)
        ax.set_title(f"{label_a} minus {label_b}\nGap MSE: {gap_mse:.3e}", fontsize=9)
        ax.set_ylim(-diff_y_max, diff_y_max)
        ax.set_xlabel("Time relative to gap start (ms)")

    diff_fig.suptitle(f"{filename_base} — pairwise differences, {burst_len_packets}-packet burst, example {example_num}",
                       fontsize=12, y=1.02)
    diff_fig.tight_layout()
    diff_fig.savefig(FIGURES_DIR / f"diff_{filename_base}_{burst_len_packets}pkt_ex{example_num}.png",
                      dpi=150, bbox_inches='tight')
    plt.show()

    mse_table = pd.DataFrame(rows)
    print(mse_table.to_string(index=False))
    return mse_table

def extract_bursts(sequence):
    """
    Extracts (start_packet_idx, burst_length) for all bursts (consecutive '1's) in a sequence.
    """
    bursts = []
    i = 0
    while i < len(sequence):
        if sequence[i] == 1:
            start_idx = i
            length = 0
            while i < len(sequence) and sequence[i] == 1:
                length += 1
                i += 1
            bursts.append((start_idx, length))
        else:
            i += 1
    return bursts

def detect_burst_lengths_in_files(filenames):
    """
    Finds all unique burst lengths that actually happened in the specified files
    and returns them in a sorted list.
    """
    all_burst_lengths = set()
    burst_examples_dict = {} # Dictionary to store examples: {burst_len: [(filename_base, start_idx), ...]}

    for name in filenames:
        trace_path = TRACES_DIR / f"{name}.txt"
        if not trace_path.exists():
            print(f"Warning: Trace file not found at {trace_path}")
            continue

        data = np.loadtxt(trace_path, dtype=int).flatten()
        if len(data) == 0:
            continue

        file_bursts = extract_bursts(data) # Use the newly defined extract_bursts
        for start_idx, length in file_bursts:
            all_burst_lengths.add(length)
            if length not in burst_examples_dict:
                burst_examples_dict[length] = []
            # Store up to 3 examples per burst length to avoid too many plots
            if len(burst_examples_dict[length]) < 3:
                burst_examples_dict[length].append((name, start_idx))

    return sorted(list(all_burst_lengths)), burst_examples_dict

