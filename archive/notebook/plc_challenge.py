def analyze_custom_lpc_sweep(list_of_coefficients, list_of_previous_samples, file_index=0):
    """
    Sweeps custom, explicit lists of LPC orders and context window lengths,
    timing the fit and plotting a single combined heatmap.
    """
    lossy_files = sorted(LOSSY_DIR.glob("*.wav"))
    audio, sr = librosa.load(lossy_files[file_index], sr=None, mono=True)

    max_prev_samples = max(list_of_previous_samples)
    max_order = max(list_of_coefficients)

    # Ensure the audio file is long enough for the largest test
    if len(audio) < max_prev_samples:
        raise ValueError(f"{lossy_files[file_index].name} has only {len(audio)} samples, "
                         f"need at least {max_prev_samples}")

    # Anchor the start position so every test analyzes the exact same acoustic event
    start_pos = max_prev_samples

    # Initialize the results grid matching the dimensions of your custom lists
    timing_ms = np.full((len(list_of_previous_samples), len(list_of_coefficients)), np.nan)

    # Warm-up the solver to absorb initialization latency
    print("Warming up the linear solver...")
    _ = ar_fit(audio[:max_order*2], max_order, LPC_DIAGONAL_LOAD)

    print(f"Running custom matrix sweep on {lossy_files[file_index].name}...")

    # The Dual Loop: Exactly mapping your specific arrays
    for i, n_prev in enumerate(list_of_previous_samples):
        clue = audio[start_pos - n_prev : start_pos]

        for j, order in enumerate(list_of_coefficients):
            if order >= n_prev:
                continue  # Skip mathematically invalid combinations

            # --- TIMER ---
            t0 = time_module.perf_counter()
            _ = ar_fit(clue, order, LPC_DIAGONAL_LOAD)
            timing_ms[i, j] = (time_module.perf_counter() - t0) * 1000

    # --- PLOTTING THE HEATMAP ---
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.set_facecolor("lightgrey") # Highlights invalid (NaN) regions

    img = ax.imshow(timing_ms, origin="lower", cmap="magma", aspect="auto")

    # Force the X and Y axes to strictly display the numbers from your custom lists
    ax.set_xticks(range(len(list_of_coefficients)))
    ax.set_xticklabels(list_of_coefficients)
    ax.set_yticks(range(len(list_of_previous_samples)))
    ax.set_yticklabels(list_of_previous_samples)

    ax.set_xlabel("Number of coefficients (LPC order)")
    ax.set_ylabel("Number of previous samples (context window)")
    ax.set_title(f"LPC fit time (ms) — Custom Sweep")

